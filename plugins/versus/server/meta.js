/** 每个对局已发过的公告（GameData 实例唯一）。 */
const announced = new WeakMap();

export default function setup(sp) {
  const settings = sp.settings || {};
  const teamSize = Number.isInteger(settings.teamSize) ? settings.teamSize : 2;
  const targetSeconds = Number.isInteger(settings.confrontTargetSeconds) ? settings.confrontTargetSeconds : 10;

  sp.meta.register('global:versus-mode', {
    onRoundStart(ctx, ev) {
      if (ev.round !== 14) return;
      let done = announced.get(ctx.gd);
      if (!done) { done = new Set(); announced.set(ctx.gd, done); }
      if (done.has('reveal')) return;
      done.add('reveal');
      ctx.log(`对抗 · 最终狩猎：对方视角已公开（每队 ${teamSize} 人，目标窗口 ${targetSeconds}s）`);
    },
  });
}
